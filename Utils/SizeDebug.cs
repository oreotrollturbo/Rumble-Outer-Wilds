using System.Collections;
using System.Linq;
using MelonLoader;
using UnityEngine;

namespace OuterWildsRumble;

/// <summary>
/// Logs the real in-game size of every body next to the size the spreadsheet says it should be.
///
/// Scale facts derived from your orbit settings:
///   1 pre-scale unit = 1213.2 m of real Outer Wilds distance (TH 8593.09 m / 7.083, GD 16457.6 m / 13.566, ...)
///   world units per metre = SolarSystemScale / 1213.2   (80 -> 0.0659 wu/m, i.e. 1 wu = 15.17 m)
///
/// Usage: MelonCoroutines.Start(SizeDebug.LogAfterFrames());  at the end of SetupSolarSystem()
/// and/or inside OwSystemSettings.OnSettingsSaved() so it re-logs every time you change the scale.
/// 
/// I was not gonna make fuckass loging myself, so yes this was generated by claude
/// </summary>
public static class SizeDebug
{
    public const float MetersPerPreScaleUnit = 1213.2f;

    private struct Body
    {
        public string Name;
        public Transform T;
        public float RadiusM;
    }

    public static IEnumerator LogAfterFrames()
    {
        // let Orbiter.Start / SolarSystemScaler run first
        yield return null;
        yield return null;
        Log();
    }

    public static void Log()
    {
        var s = Main.solarSystem;
        if (s.Root == null) return;

        float scale = s.Root.transform.lossyScale.x;
        float wuPerMeter = scale / MetersPerPreScaleUnit;

        var bodies = new[]
        {
            new Body { Name = "Sun", T = s.Sun?.transform, RadiusM = 2001.75f },
            // the two children of the HourGlassTwins root are the planets (same indices the quantum moon uses)
            new Body { Name = "Ember/Ash twin (child 0)", T = s.HourGlassTwins?.transform.GetChild(0), RadiusM = 170f },
            new Body { Name = "Ember/Ash twin (child 2)", T = s.HourGlassTwins?.transform.GetChild(2), RadiusM = 169f },
            new Body { Name = "Timber Hearth", T = s.TimberHearth?.transform, RadiusM = 254f },
            new Body { Name = "Attlerock", T = s.Attlerock?.transform, RadiusM = 80f },
            new Body { Name = "Brittle Hollow", T = s.BrittleHollow?.transform, RadiusM = 272f },
            new Body { Name = "Hollow's Lantern", T = s.HollowsLantern?.transform, RadiusM = 97.3f },
            new Body { Name = "Giant's Deep", T = s.GiantsDeep?.transform, RadiusM = 500f },
            new Body { Name = "Dark Bramble", T = s.DarkBramble?.transform, RadiusM = 203.3f },
            new Body { Name = "Interloper", T = s.Interloper?.transform, RadiusM = 83f },
            new Body { Name = "Quantum Moon", T = s.QuantumMoon?.transform, RadiusM = 73f },
        };

        MelonLogger.Msg($"[SizeDebug] solar system scale = {scale}  ->  {wuPerMeter:F5} world units per metre " +
                        $"(1 wu = {1f / wuPerMeter:F2} m)");

        foreach (var b in bodies)
        {
            if (b.T == null) continue;

            float targetDiamWu = 2f * b.RadiusM * wuPerMeter;
            MelonLogger.Msg($"[SizeDebug] {b.Name}: spreadsheet radius {b.RadiusM} m -> should be {targetDiamWu:F2} wu across " +
                            $"(localScale {b.T.localScale.x:F4})");

            // Largest few renderers under this body. The planet itself is normally the biggest *solid* one,
            // but atmospheres / clouds / ocean shells can be bigger, so look at the list and pick the right line.
            var sizes = b.T.GetComponentsInChildren<Renderer>(true)
                .Select(r => new { r, d = MeshDiameter(r) })
                .Where(x => x.d > 0f)
                .OrderByDescending(x => x.d)
                .Take(4);

            foreach (var x in sizes)
            {
                float apparentRadiusM = x.d / 2f / wuPerMeter;
                float fix = b.RadiusM / apparentRadiusM; // multiply the body's localScale by this
                MelonLogger.Msg($"    {PathFrom(x.r.transform, b.T)}: {x.d:F2} wu across = radius {apparentRadiusM:F0} m " +
                                $"(x{fix:F3} to match)");
            }
        }
    }

    /// <summary>
    /// Diameter in world units, using the mesh bounds times lossyScale. Unlike Renderer.bounds this
    /// ignores rotation (no inflated axis-aligned box) and still works on inactive objects
    /// (realistic mode switches off the anchor planet's children).
    /// </summary>
    private static float MeshDiameter(Renderer r)
    {
        var mf = r.GetComponent<MeshFilter>();
        if (mf != null && mf.sharedMesh != null)
        {
            Vector3 size = mf.sharedMesh.bounds.size;
            Vector3 ls = r.transform.lossyScale;
            return Mathf.Max(size.x * ls.x, size.y * ls.y, size.z * ls.z);
        }

        // SkinnedMeshRenderer etc: fall back to world bounds
        Vector3 bs = r.bounds.size;
        return Mathf.Max(bs.x, bs.y, bs.z);
    }

    private static string PathFrom(Transform t, Transform root)
    {
        if (t == root) return "(root)";
        string p = t.name;
        while (t.parent != null && t.parent != root)
        {
            t = t.parent;
            p = t.name + "/" + p;
        }

        return p;
    }
}